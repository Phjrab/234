  function registerStatic() {
    // Register the original HTML once, before app.js renders user content.
    // Explicit source-node references avoid translating later input/data nodes.
    if (!document.createTreeWalker) return;
    const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (node.parentElement?.closest('script, style, textarea, pre, code')) continue;
      const key = node.data.trim();
      if (!Object.hasOwn(korean, key)) continue;
      staticText.push({node, key, leading: node.data.match(/^\s*/)[0], trailing: node.data.match(/\s*$/)[0]});
    }
    for (const element of document.querySelectorAll('[aria-label], [title], [placeholder]')) {
      for (const name of ['aria-label', 'title', 'placeholder']) {
        const key = element.getAttribute(name);
        if (key && Object.hasOwn(korean, key)) staticAttributes.push({element, name, key});
      }
    }
    applyStatic();
  }

