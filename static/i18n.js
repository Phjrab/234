  const storageKey = 'forge.language';
  const supported = new Set(['en', 'ko']);
  let language = 'en';
  try {
    const saved = localStorage.getItem(storageKey);
    if (supported.has(saved)) language = saved;
  } catch { /* Keep the interface usable when browser storage is disabled. */ }

  const staticText = [];
  const staticAttributes = [];
  const numericMessages = [
    ['{budget} GB VRAM is an explicit planning assumption. This heuristic does not measure hardware, tokenize data or guarantee that any model/configuration fits.', 'budget'],
    ['Heuristic memory estimate exceeds the assumed {budget} GB budget; reduce context, batch or rank and validate with a real worker.', 'budget'],
    ['Heuristic memory estimate leaves limited headroom within the assumed {budget} GB budget.', 'budget'],
    ['Exact normalized duplicate of line {line}; retained unless you edit the source.', 'line'],
    ['{count} validation record(s) have exact duplicates in training; edit or deduplicate the source before using this split for evaluation.', 'count']
  ].map(([key, field]) => ({key, field, pattern: new RegExp('^' + key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace('\\{' + field + '\\}', '(\\d+(?:\\.\\d+)?)') + '$')}));
  const translate = (message, values = {}) => {
    let text = language === 'ko' && Object.hasOwn(korean, message) ? korean[message] : String(message ?? '');
    if (language === 'ko' && !Object.hasOwn(korean, message)) {
      for (const entry of numericMessages) {
        const match = text.match(entry.pattern);
        if (match) { text = korean[entry.key]; values = {[entry.field]: match[1], ...values}; break; }
      }
    }
    return text.replace(/\{(\w+)\}/g, (placeholder, key) => Object.hasOwn(values, key) ? String(values[key]) : placeholder);
  };

  function applyStatic() {
    if (document.documentElement) document.documentElement.lang = language;
    for (const entry of staticText) {
      if (entry.node.isConnected) entry.node.data = entry.leading + translate(entry.key) + entry.trailing;
    }
    for (const entry of staticAttributes) {
      if (entry.element.isConnected) entry.element.setAttribute(entry.name, translate(entry.key));
    }
  }

  function registerStatic() {
    // Register the original HTML once, before app.js renders user content.
    // Explicit source-node references avoid translating later input/data nodes.
    if (!document.createTreeWalker) return;
    const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (node.parentElement?.closest('script, style, textarea, pre, code')) continue;
      const key = node.data.trim();
      if (!Object.hasOwn(korean, key)) continue;
      staticText.push({node, key, leading: node.data.match(/^\s*/)[0], trailing: node.data.match(/\s*$/)[0]});
    }
    for (const element of document.querySelectorAll('[aria-label], [title], [placeholder]')) {
      for (const name of ['aria-label', 'title', 'placeholder']) {
        const key = element.getAttribute(name);
        if (key && Object.hasOwn(korean, key)) staticAttributes.push({element, name, key});
      }
    }
    applyStatic();
  }

  function setLanguage(next, persist = true) {
    if (!supported.has(next) || next === language) return false;
    language = next;
    if (persist) {
      try { localStorage.setItem(storageKey, language); } catch { /* In-memory selection still works. */ }
    }
    applyStatic();
    if (document.dispatchEvent && globalThis.CustomEvent) document.dispatchEvent(new CustomEvent('forge:languagechange', {detail: {language}}));
    return true;
  }

  registerStatic();
  globalThis.addEventListener?.('storage', event => {
    if (event.key === storageKey) setLanguage(event.newValue || 'en', false);
  });
  return Object.freeze({translate, setLanguage, applyStatic, get language() { return language; }});
